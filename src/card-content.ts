// ponytail: only this card's two mapping levels; use a YAML library if the schema gains deeper nesting.
export const initialYaml = Object.entries(initialState)
  .map(
    ([group, values]) =>
      `${group}:\n${Object.entries(values)
        .map(([key, value]) =>
          Array.isArray(value)
            ? `  ${key}:\n${value.map((item) => `    - ${JSON.stringify(item)}`).join("\n")}`
            : `  ${key}: ${JSON.stringify(value)}`,
        )
        .join("\n")}`,
  )
  .join("\n");

function entry(id: number, name: string, content: string, enabled = true) {
  return {
    id,
    keys: [],
    secondary_keys: [],
    comment: name,
    content,
    constant: true,
    selective: false,
    insertion_order: 100 - id,
    enabled,
    position: "before_char",
    extensions: {},
  };
}

// Story entries never recursively activate one another. Technical entry defaults stay unchanged.
// ST 1.17.0 / aa50edcf4: convertCharacterBook maps these extension names directly.
function storyEntry(
  id: number,
  name: string,
  content: string,
  keys: string[] = [],
) {
  return {
    ...entry(id, name, content),
    keys,
    constant: keys.length === 0,
    extensions: {
      exclude_recursion: true,
      prevent_recursion: true,
      scan_depth: 4,
      case_sensitive: false,
      match_whole_words: false,
      probability: 100,
      useProbability: true,
      ignore_budget: false,
    },
  };
}

